-- Момент последнего успешного входа — отдельно от created_at (момент
-- ПЕРВОГО входа, см. 000001_init.up.sql). Нужен админ-таблице
-- (google-auth/src/admin.cpp, GET /admin/users) — "когда пользователь
-- заходил в последний раз" не восстановить из created_at, а Redis
-- (access/refresh-токены) хранит только СЕЙЧАС активные сессии, TTL которых
-- истекает, а не историю последнего входа.
--
-- Нет DEFAULT — на существующих строках (заведённых до этой миграции)
-- значение остаётся NULL, то есть "не знаем" (пусто в API, см. repo.cpp),
-- а не выдуманная дата. Проставляется repo::upsert_user на КАЖДЫЙ логин
-- (в отличие от role_id, который меняется только явной правкой в БД,
-- last_login_at — не авторизационное состояние, обновлять его на каждый
-- вход безопасно и правильно).
ALTER TABLE users ADD COLUMN last_login_at TIMESTAMPTZ;

COMMENT ON COLUMN users.last_login_at IS
    'Момент последнего успешного входа — обновляется на КАЖДЫЙ логин (в отличие от created_at — только первый). NULL у строк, заведённых до появления этой колонки и ни разу не логинившихся после.';
